export type SubcompetencyCode = (typeof EXAM_CURRICULUM)[number]["code"];
export type CoverageRow = {
  subcompetency_code?: string | null;
  published?: number;
  drafts?: number;
};
export function curriculumCoverage(rows: CoverageRow[]) {
  return EXAM_CURRICULUM.map((s) => {
    const group = rows.filter((r) => r.subcompetency_code === s.code);
    const published = group.reduce((n, r) => n + (Number(r.published) || 0), 0);
    const drafts = group.reduce((n, r) => n + (Number(r.drafts) || 0), 0);
    return {
      ...s,
      published,
      drafts,
      missing: Math.max(0, s.quota - published),
      targetMissing: Math.max(0, s.target - published),
    };
  });
}
export function isCurriculumPair(competency: string, subcompetency: string) {
  return EXAM_CURRICULUM.some(
    (s) => s.code === subcompetency && s.competency === competency,
  );
}
